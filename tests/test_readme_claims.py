"""Assert the hand-written v1/v2 narrative numbers against results/.

These passages were written for the pre-v3 README, which now lives at docs/v2_history.md
(the current README.md covers V3/V4). Its tables live inside `<!-- NAME -->` markers, are
regenerated by scripts/update_readme.py, and CI fails on any drift. The prose around them is not
generated -- templating sentences that pull from four different CSVs would be brittle and
hard to read -- so the two numeric passages most likely to be quoted outside the repo
("Four findings worth reading this repo for" and "What the grid says") are pinned here
instead.

Each check anchors on a distinctive phrase and compares the figure printed in the README
with the figure recomputed from the committed CSV/JSON, at the rounding the README uses.
A reworded sentence fails loudly rather than silently skipping the check: that is intended.

Rounding convention. The ablation prose quotes differences between the mean-AUC cells the
README prints to four decimals, so the deltas here are computed the way a reader checks
them -- round each mean to 4 dp first, then subtract -- and the front-page sentence rounds
those 4 dp deltas again to 3. Half-up throughout, as a person rounds by hand.
"""

from __future__ import annotations

import csv
import json
import re
import sys
import unittest
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

RESULTS = ROOT / "results"
# The archived pre-v3 README, where the v1/v2 findings below are published.
ARCHIVED_README = ROOT / "docs" / "v2_history.md"
# Whitespace-flattened, so a re-wrapped paragraph does not break every pattern below.
README = re.sub(r"\s+", " ", ARCHIVED_README.read_text(encoding="utf-8"))


def rnd(value: float, places: int) -> float:
    quant = Decimal(1).scaleb(-places)
    return float(Decimal(repr(value)).quantize(quant, rounding=ROUND_HALF_UP))


def _rows(path: Path) -> list[dict]:
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def _auc_by_head(path: Path) -> dict[tuple[str, str], float]:
    return {(r["transform"], r["head"]): float(r["auc"]) for r in _rows(path)}


def _mean_transformed(path: Path, head: str) -> float:
    vals = [float(r["auc"]) for r in _rows(path) if r["head"] == head and r["transform"] != "clean"]
    return sum(vals) / len(vals)


def _mean_tpr(path: Path) -> float:
    rows = [r for r in _rows(path) if r["transform"] != "clean"]
    return sum(float(r["tpr_at_1fpr"]) for r in rows) / len(rows)


def _ablation_delta(head: str) -> float:
    """Delta the reader can check against the printed 4 dp table: round, then subtract."""
    table = RESULTS / "ablation_table.csv"
    base = rnd(_mean_transformed(table, "clip_only_4v"), 4)
    return rnd(rnd(_mean_transformed(table, head), 4) - base, 4)


class ReadmeClaimTests(unittest.TestCase):
    """Every assertion here is `archived README text` vs `recomputed from results/`."""

    def _find(self, pattern: str) -> tuple[str, ...]:
        match = re.search(pattern, README)
        self.assertIsNotNone(
            match,
            f"docs/v2_history.md no longer contains the passage this test pins:\n  {pattern}\n"
            "Update the pattern together with the sentence, or restore the claim.",
        )
        return match.groups()

    # ---------------------------------------------------- Four findings (front page)
    def test_finding1_cross_source_thumbnail(self):
        cross = _auc_by_head(RESULTS / "ablation_demo_table.csv")
        baseline, forensic = self._find(
            r"scores ([0-9.]+) on thumbnails of an unseen generator .{0,40}? "
            r"the forensic branch lifts it to ([0-9.]+)\."
        )
        self.assertEqual(float(baseline), rnd(cross[("resize_0.25", "clip_only_4v")], 2))
        self.assertEqual(float(forensic), rnd(cross[("resize_0.25", "forensic_4v")], 2))

    def test_finding2_noise_collapse_and_interaction(self):
        ind = _auc_by_head(RESULTS / "ablation_table.csv")
        clip_only, forensic = self._find(
            r"collapses under noise\*\* \(([0-9.]+) -> ([0-9.]+) at sigma 0\.10\)"
        )
        self.assertEqual(float(clip_only), rnd(ind[("noise_0.10", "clip_only_4v")], 3))
        self.assertEqual(float(forensic), rnd(ind[("noise_0.10", "forensic_4v")], 3))

        alone_forensic, alone_noise, both = self._find(
            r"Alone they are worth (-[0-9.]+) and \+([0-9.]+); together \+([0-9.]+)\."
        )
        self.assertEqual(float(alone_forensic), rnd(_ablation_delta("forensic_4v"), 3))
        self.assertEqual(float(alone_noise), rnd(_ablation_delta("clip_only_5v"), 3))
        self.assertEqual(float(both), rnd(_ablation_delta("forensic_5v"), 3))

    def test_finding3_leakage_control(self):
        summary = json.loads((RESULTS / "leakage" / "summary.json").read_text(encoding="utf-8"))
        worst_delta = max(abs(v) for key in ("delta_x1", "delta_x2") for v in summary[key].values())
        blockiness = summary["probes"]["blockiness_8px"]["separability"]
        bound, sep = self._find(
            r"moves every head by <= \+([0-9.]+) AUC; a bare blockiness scalar separates "
            r"the classes at only ([0-9.]+)\."
        )
        self.assertEqual(float(bound), rnd(worst_delta, 4))
        self.assertEqual(float(sep), rnd(blockiness, 3))

    def test_jpeg_control_is_not_stated_as_proof(self):
        # The control only failed to detect a JPEG-history shortcut. The two sentences that
        # once presented it as proof were withdrawn; keep them out of every published page.
        withdrawn = ("not reading jpeg history", "shows it is not cheating")
        pages = [ROOT / "README.md", *sorted((ROOT / "docs").glob("*.md"))]
        self.assertIn(ARCHIVED_README, pages)
        for page in pages:
            text = re.sub(r"\s+", " ", page.read_text(encoding="utf-8")).lower()
            for phrase in withdrawn:
                self.assertNotIn(phrase, text, f"{page.name} restores a withdrawn claim")
        self.assertIn("does not rule out source or compression bias", README)
        current = re.sub(r"\s+", " ", (ROOT / "README.md").read_text(encoding="utf-8"))
        self.assertIn("does not prove that source/compression bias is absent", current)

    def test_finding4_v1_to_v2(self):
        deltas = [float(r["delta_auc"]) for r in _rows(RESULTS / "ab_v1_v2.csv")]
        mean_claim, count, lo, hi, tpr_v1, tpr_v2 = self._find(
            r"is worth \+([0-9.]+) AUC everywhere\.\*\* .{0,200}? "
            r"lifts all (\d+) conditions by \+([0-9.]+) to \+([0-9.]+) AUC "
            r"and the mean TPR at 1% FPR from ([0-9.]+) to ([0-9.]+);"
        )
        self.assertEqual(int(count), len(deltas))
        self.assertEqual(float(mean_claim), rnd(sum(deltas) / len(deltas), 3))
        self.assertEqual(float(lo), rnd(min(deltas), 3))
        self.assertEqual(float(hi), rnd(max(deltas), 3))
        self.assertEqual(float(tpr_v1), rnd(_mean_tpr(RESULTS / "v1" / "robustness_table.csv"), 2))
        self.assertEqual(float(tpr_v2), rnd(_mean_tpr(RESULTS / "robustness_table.csv"), 2))

    # ---------------------------------------------------- "What the grid says"
    def test_grid_item1_cross_source_lift(self):
        cross = _auc_by_head(RESULTS / "ablation_demo_table.csv")
        clean, thumb, lift_clean, lift_thumb = self._find(
            r"a UnivFD-style probe scores ([0-9.]+) clean and \*\*([0-9.]+) on quarter-scale "
            r"thumbnails .{0,40}?\*\*\. The forensic branch lifts that by \+([0-9.]+) and \+([0-9.]+)\."
        )
        self.assertEqual(float(clean), rnd(cross[("clean", "clip_only_4v")], 2))
        self.assertEqual(float(thumb), rnd(cross[("resize_0.25", "clip_only_4v")], 2))
        self.assertEqual(
            float(lift_clean),
            rnd(cross[("clean", "forensic_4v")] - cross[("clean", "clip_only_4v")], 2),
        )
        self.assertEqual(
            float(lift_thumb),
            rnd(cross[("resize_0.25", "forensic_4v")] - cross[("resize_0.25", "clip_only_4v")], 2),
        )

    def test_grid_item3_interaction_four_decimals(self):
        noise, forensic, both = self._find(
            r"Alone it is worth \+([0-9.]+); forensic alone is worth -([0-9.]+); "
            r"together they are worth \+([0-9.]+)\."
        )
        self.assertEqual(float(noise), _ablation_delta("clip_only_5v"))
        self.assertEqual(-float(forensic), _ablation_delta("forensic_4v"))
        self.assertEqual(float(both), _ablation_delta("forensic_5v"))

    def test_grid_item4_beats_baseline_everywhere(self):
        ind = _auc_by_head(RESULTS / "ablation_table.csv")
        names = sorted({t for t, _ in ind})
        cross = _auc_by_head(RESULTS / "ablation_demo_table.csv")
        wins, total, worst_base, worst_v1, lo, hi = self._find(
            r"baseline on (\d+) / (\d+) in-distribution rows\*\* \(worst row ([0-9.]+) -> ([0-9.]+)\) "
            r"and by \+([0-9.]+) to \+([0-9.]+) on every cross-source row\."
        )
        self.assertEqual(int(total), len(names))
        self.assertEqual(
            int(wins), sum(1 for t in names if ind[(t, "forensic_5v")] > ind[(t, "clip_only_4v")])
        )
        self.assertEqual(float(worst_base), min(ind[(t, "clip_only_4v")] for t in names))
        self.assertEqual(float(worst_v1), min(ind[(t, "forensic_5v")] for t in names))
        deltas = [
            cross[(t, "forensic_5v")] - cross[(t, "clip_only_4v")]
            for t in sorted({t for t, _ in cross})
        ]
        self.assertEqual(float(lo), rnd(min(deltas), 2))
        self.assertEqual(float(hi), rnd(max(deltas), 2))


if __name__ == "__main__":
    unittest.main()
